# cut_table.py <PARITY_DIR> <out.inc>  — fit every measured Channel EQ low-cut render and emit the engine's cut table.
# Each render is a low cut at 200 Hz with one slope code and one shown Q. Fits are a cascade of first-order and
# second-order sections; the table stores, per shown Q, each section's corner relative to the set frequency
# (first order: Hz ratio; second order: ratio of prewarped tan(pi f / fs)) and each biquad's Q.
import sys, os, re, json, shlex, numpy as np, warnings
from scipy.io import wavfile
from scipy.signal import sosfilt
from scipy.optimize import least_squares
warnings.filterwarnings('ignore')
S, OUT = sys.argv[1], sys.argv[2]; fs = 44100; F0 = 200.0; K0 = np.tan(np.pi * F0 / fs)
T = {'0': 'Audio 1', '5': 'Audio 6', '6': 'Audio 7', '7': 'Audio 8', '8': 'Audio 9'}
seg = slice(int(0.5 * fs), int(16 * fs))
def wav(p): return wavfile.read(p)[1][:, 0].astype(np.float64)
def load(run, t):
    x = wav(f'{S}/renders/bypass/{t}_1.wav')[seg]
    if os.path.exists(f'{S}/renders/{run}.npz'): return x, np.load(f'{S}/renders/{run}.npz')[t]
    xr, yr = wav(f'{S}/renders/bypass/Audio 10_1.wav'), wav(f'{S}/renders/{run}/Audio 10_1.wav')
    return x, wav(f'{S}/renders/{run}/{t}_1.wav')[seg] / ((xr @ yr) / (xr @ xr))
def norm(b, a): return list(np.array(b) / a[0]) + list(np.array(a) / a[0])
def build(order, p):
    sos, i = [], 0
    if order % 2:
        K = np.tan(np.pi * F0 * p[0] / fs); sos.append(norm([1, -1, 0], [1 + K, K - 1, 0])); i = 1
    while i < len(p):
        K, q = K0 * p[i], p[i + 1]; d = 1 + K / q + K * K
        sos.append(norm([1, -2, 1], [d, 2 * (K * K - 1), 1 - K / q + K * K])); i += 2
    return np.array(sos)
def fit(run, t, order, init):
    x, y = load(run, t)
    r = least_squares(lambda lp: y - sosfilt(build(order, np.exp(lp)), x), np.log(np.array(init) * 1.0001), x_scale=0.1, xtol=1e-15, ftol=1e-15)
    e = r.fun; return list(np.exp(r.x)), 10 * np.log10((e @ e) / (y @ y))
def butter(order):
    p = [1.0] if order % 2 else []
    for k in range(1, order // 2 + 1): p += [1.0, 1 / (2 * np.sin((2 * k - 1) * np.pi / (2 * order)))]
    return p
shown = sorted(set(float('%.2g' % 10 ** (-1 + 3 * i / 127)) for i in range(128)))
def snap(q): return min(shown, key=lambda s: (abs(s - q), s))
# Which render holds which (order, Q): parse batch specs "<ch> 0=1 1=200 2=<code> 3=<q>".
specs = {}
for line in open(f'{S}/sweep.txt'):
    name, rest = line.split(' ', 1)
    specs[name] = [tuple(s.split()) for s in shlex.split(rest)]
for c in [2, 3, 4, 6, 8]: specs[f'bp{c}'] = [(ch, '0=1', '1=200', f'2={c}', f'3={q}') for ch, q in zip('05678', [.1, .5, .70710678, 1])]
specs['mid1'] = [(ch, '0=1', '1=200', f'2={c}', f'3={q}') for ch, (c, q) in zip('05678', [(4, .84), (4, .6), (3, .84), (6, .84), (8, .84)])]
specs['mid2'] = [(ch, '0=1', '1=200', f'2={c}', f'3={q}') for ch, (c, q) in zip('5678', [(4, .2), (3, .6), (6, .6), (8, .3)])]
specs['lc3'] = [('0', '0=1', '1=200', '2=2', '3=0.3'), ('8', '0=1', '1=200', '2=4', '3=0.3')]
specs['lc4'] = [('7', '0=1', '1=200', '2=3', '3=0.3'), ('8', '0=1', '1=200', '2=6', '3=0.3')]
cache_path = f'{S}/cut_fits.json'
cache = json.load(open(cache_path)) if os.path.exists(cache_path) else {}
items = []
for run, lst in specs.items():
    # A sweep batch counts once compacted (sweep.sh compacts after the export finishes).
    if not (os.path.exists(f'{S}/renders/{run}.npz') or (not run.startswith('sw') and os.path.isdir(f'{S}/renders/{run}'))): continue
    for s in lst:
        kv = dict(a.split('=') for a in s[1:]); items.append((int(kv['2']), snap(float(kv['3'])), run, T[s[0]]))
for order in [2, 3, 4, 6, 8]:
    # Fit from Q = 1 downwards, starting each fit from the neighbour's result.
    prev = butter(order)
    for c, q, run, t in sorted((i for i in items if i[0] == order), key=lambda i: -i[1]):
        key = f'{c}/{q}'
        if key in cache and cache[key]['null'] < -120: prev = cache[key]['p']; continue
        best = None
        for init in (prev, butter(order)):
            p, null = fit(run, t, c, init)
            if best is None or null < best[1]: best = (p, null)
            if null < -130: break
        cache[key] = {'p': best[0], 'null': best[1], 'run': run}; prev = best[0]
        print(f'order {c} Q {q}: null {best[1]:.1f} dB', flush=True)
        json.dump(cache, open(cache_path, 'w'), indent=1)
bad = {k: round(v['null'], 1) for k, v in cache.items() if v['null'] > -120}
if bad: print('poor fits:', bad)
# Emit the table: rows sorted by Q, sections ordered most resonant first.
with open(OUT, 'w') as f:
    f.write('// Generated by tools/logic-parity/cut_table.py from Logic Channel EQ renders (measured, not transcribed).\n')
    f.write('// Row: shown Q, first-order corner ratio (0 if none), then up to four biquads as {tan-domain corner ratio, Q}.\n')
    for order in [2, 3, 4, 6, 8]:
        rows = sorted(((float(k.split('/')[1]), v['p']) for k, v in cache.items() if k.split('/')[0] == str(order)))
        f.write(f'constexpr CutRow kCut{order}[] = {{\n')
        for q, p in rows:
            first = p[0] if order % 2 else 0.0
            secs = sorted([(p[i], p[i + 1]) for i in range(order % 2, len(p), 2)], key=lambda s: -s[1])
            secs += [(1.0, 0.0)] * (4 - len(secs))
            f.write(f'    {{{q!r}, {first:.9g}, {{' + ', '.join(f'{{{r:.9g}, {qq:.9g}}}' for r, qq in secs) + '}},\n')
        f.write('};\n')
print('wrote', OUT)
