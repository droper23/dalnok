#!/usr/bin/env python3
"""Generates the model views (A-15) from engine/api/views.def: the C structs in dalnok.h, the engine code that
fills them and the Swift field structs the app decodes them into. `--check` fails if anything is out of date.
SPDX-License-Identifier: GPL-3.0-or-later"""
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
DEF = os.path.join(ROOT, 'engine/api/views.def')
HEADER = os.path.join(ROOT, 'engine/include/dalnok/dalnok.h')
FILL_DIR = os.path.join(ROOT, 'engine/src/generated')
SWIFT = os.path.join(ROOT, 'app/macos/Dalnok/Generated/ModelViews.swift')
NOTE = 'Generated by scripts/gen-api.py from engine/api/views.def. Do not edit.'

SWIFT_TYPES = {'bool': 'Bool', 'int32_t': 'Int32', 'int64_t': 'Int64', 'float': 'Float', 'double': 'Double',
               'DalnokTrackId': 'DalnokTrackId', 'DalnokClipId': 'DalnokClipId', 'DalnokMediaId': 'DalnokMediaId'}


def parse():
    structs, cur = [], None
    for n, raw in enumerate(open(DEF), 1):
        line = raw.split('#', 1)[0].rstrip() if not raw.lstrip().startswith('#') else ''
        if not line.strip():
            continue
        if line.startswith('struct '):
            head, _, context = line[len('struct '):].partition(':')
            c_name, swift_name = head.split()
            cur = {'c': c_name, 'swift': swift_name, 'context': context.strip(), 'fields': []}
            continue
        if line.strip() == 'end':
            structs.append(cur)
            cur = None
            continue
        if cur is None:
            sys.exit(f'{DEF}:{n}: field outside a struct')
        parts = [p.strip() for p in re.split(r'(?<=\s)\|(?=\s|$)', line)]  # a lone | between spaces ('||' stays)
        if len(parts) != 4:
            sys.exit(f'{DEF}:{n}: expected "<type> <name> | <swiftName> | <expression> | <comment>"')
        ctype, cname = parts[0].split()
        m = re.fullmatch(r'char\[(\d+)\]', ctype)
        if not m and ctype not in SWIFT_TYPES:
            sys.exit(f'{DEF}:{n}: unknown type {ctype}')
        cur['fields'].append({'ctype': ctype, 'name': cname, 'swift': parts[1], 'expr': parts[2], 'comment': parts[3],
                              'chars': int(m.group(1)) if m else 0})
    return structs


def c_struct(s):
    lines = ['typedef struct {']
    for f in s['fields']:
        decl = f'char {f["name"]}[{f["chars"]}];' if f['chars'] else f'{f["ctype"]} {f["name"]};'
        lines.append(f'    {decl:<30}' + (f' /* {f["comment"]} */' if f['comment'] else '').rstrip())
    lines.append(f'}} {s["c"]};')
    return '\n'.join(l.rstrip() for l in lines)


def fill(s):
    out = [f'// {NOTE}', f'// Fills `{s["c"]} *out` from: {s["context"]}.', f'*out = {s["c"]}{{}};']
    for f in s['fields']:
        if f['chars']:
            out.append(f'copyOut(out->{f["name"]}, sizeof out->{f["name"]}, {f["expr"]});')
        else:
            out.append(f'out->{f["name"]} = {f["expr"]};')
    return '\n'.join(out) + '\n'


def swift(structs):
    out = [f'// {NOTE}', '// The fields of each C API model view, decoded once (strings included). App views hold one of these and',
           '// reach its fields through dynamic member lookup, so a field added to views.def needs no Swift edit.',
           '// SPDX-License-Identifier: GPL-3.0-or-later', 'import DalnokEngine', '']
    for s in structs:
        out.append(f'struct {s["swift"]}: Equatable {{')
        for f in s['fields']:
            t = 'String' if f['chars'] else SWIFT_TYPES[f['ctype']]
            out.append(f'    var {f["swift"]}: {t}' + (f' // {f["comment"]}' if f['comment'] else ''))
        out.append('}')
        out.append(f'extension {s["swift"]} {{')
        out.append(f'    init(_ c: {s["c"]}) {{')
        args = []
        for f in s['fields']:
            args.append(f'{f["swift"]}: fixedString(c.{f["name"]})' if f['chars'] else f'{f["swift"]}: c.{f["name"]}')
        out.append(f'        self.init({", ".join(args)})')
        out.append('    }')
        out.append('}')
        out.append('')
    return '\n'.join(out)


def header_with(text, structs):
    for s in structs:
        begin, end = f'/* BEGIN GENERATED {s["c"]} (scripts/gen-api.py) */', f'/* END GENERATED {s["c"]} */'
        pattern = re.compile(re.escape(begin) + r'.*?' + re.escape(end), re.S)
        block = f'{begin}\n{c_struct(s)}\n{end}'
        if not pattern.search(text):
            sys.exit(f'{HEADER}: no GENERATED markers for {s["c"]}')
        text = pattern.sub(lambda _: block, text)
    return text


def main():
    check = '--check' in sys.argv
    structs = parse()
    wanted = {HEADER: header_with(open(HEADER).read(), structs), SWIFT: swift(structs)}
    for s in structs:
        wanted[os.path.join(FILL_DIR, s['c'] + '.inc')] = fill(s)
    stale = []
    for path, text in wanted.items():
        current = open(path).read() if os.path.exists(path) else None
        if current == text:
            continue
        stale.append(os.path.relpath(path, ROOT))
        if not check:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, 'w').write(text)
    if check and stale:
        sys.exit('out of date (run scripts/gen-api.py): ' + ', '.join(stale))
    print(('up to date' if not stale else 'wrote ' + ', '.join(stale)) if not check else 'generated API views: up to date')


if __name__ == '__main__':
    main()
